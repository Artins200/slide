# ---------- переходы между слайдами ----------
def set_transition(slide, kind="fade", dur=650):
    sld = slide._element
    for el in sld.findall(qn('p:transition')):
        sld.remove(el)
    trans = sld.makeelement(qn('p:transition'), {'spd': 'med', 'dur': str(dur)})
    if kind == "push":
        child = sld.makeelement(qn('p:push'), {'dir': 'l'})
    elif kind == "wipe":
        child = sld.makeelement(qn('p:wipe'), {'dir': 'l'})
    elif kind == "cover":
        child = sld.makeelement(qn('p:cover'), {'dir': 'r'})
    elif kind == "split":
        child = sld.makeelement(qn('p:split'), {'orient': 'horz', 'dir': 'out'})
    else:
        child = sld.makeelement(qn('p:fade'), {})
    trans.append(child)
    # p:transition должен стоять после cSld и clrMapOvr
    idx = 0
    for i, ch in enumerate(list(sld)):
        if ch.tag in (qn('p:cSld'), qn('p:clrMapOvr')):
            idx = i + 1
    sld.insert(idx, trans)


