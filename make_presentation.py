# ---------- простые helpers, без «дизайнерских» наворотов ----------
def bg(slide, img="bg_light.jpg"):
    slide.shapes.add_picture(A(img), Inches(0), Inches(0), Inches(W), Inches(H))


def box(slide, x, y, w, h, fill=WHITE, line=BORDER, round_=True):
    shp = slide.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE if round_ else MSO_SHAPE.RECTANGLE,
        Inches(x), Inches(y), Inches(w), Inches(h))
    if round_:
        try:
            shp.adjustments[0] = 0.04
        except Exception:
            pass
    shp.fill.solid(); shp.fill.fore_color.rgb = fill
    shp.line.color.rgb = line; shp.line.width = Pt(1)
    shp.shadow.inherit_shadow = False
    return shp


def text(slide, x, y, w, h, items, size=14, color=DARK, bold=False, align=PP_ALIGN.LEFT):
    """items: список строк или (строка, dict) """
    tx = slide.shapes.add_textbox(Inches(x), Inches(y), Inches(w), Inches(h))
    tf = tx.text_frame; tf.word_wrap = True
    for i, it in enumerate(items):
        if isinstance(it, tuple):
            txt, kw = it
        else:
            txt, kw = it, {}
        p = tf.paragraphs[0] if i == 0 else tf.add_paragraph()
        p.text = txt
        p.font.size = Pt(kw.get("size", size))
        p.font.bold = kw.get("bold", bold)
        p.font.italic = kw.get("italic", False)
        p.font.color.rgb = kw.get("color", color)
        p.font.name = "Calibri"
        p.alignment = kw.get("align", align)
        p.space_after = Pt(kw.get("after", 6))
        p.space_before = Pt(kw.get("before", 0))
        p.line_spacing = 1.08
    return tx


def head(slide, n, title, sub=None):
    bg(slide)
