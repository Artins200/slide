def add_bg(slide, color):
    bg = slide.background
    fill = bg.fill
    fill.solid()
    fill.fore_color.rgb = color


def shape(slide, left, top, width, height, fill=None, line=None, radius=None):
    shp_type = MSO_SHAPE.ROUNDED_RECTANGLE if radius else MSO_SHAPE.RECTANGLE
    shp = slide.shapes.add_shape(shp_type, Inches(left), Inches(top), Inches(width), Inches(height))
    shp.line.fill.background()
    if radius:
        try:
            shp.adjustments[0] = 0.08
        except Exception:
            pass
    if fill is None:
        shp.fill.background()
    else:
        shp.fill.solid()
        shp.fill.fore_color.rgb = fill
    if line is not None:
        shp.line.color.rgb = line
        shp.line.width = Pt(1)
    else:
        shp.line.fill.background()
    shp.shadow.inherit_shadow = False
    return shp


def txt_box(slide, left, top, width, height, auto=None):
    tx = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height))
    tf = tx.text_frame
    tf.word_wrap = True
    if auto:
        tf.auto_size = auto
    return tx, tf


def para(tf, text, size=14, bold=False, color=DARK, align=PP_ALIGN.LEFT,
         font="Calibri", space_after=Pt(6), space_before=Pt(0), italic=False, first=False):
    if first:
        p = tf.paragraphs[0]
    else:
        p = tf.add_paragraph()
    p.text = text
    p.font.size = Pt(size)
    p.font.bold = bold
    p.font.color.rgb = color
    p.font.name = font
    p.font.italic = italic
    p.alignment = align
    p.space_after = space_after
    p.space_before = space_before
    p.line_spacing = 1.05
    return p


